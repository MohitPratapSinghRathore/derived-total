def main() -> int:
    src = io.open(SRC, encoding="utf-8").read()
    body = src.split(r"\begin{document}", 1)[1]
    body = body.split(r"\end{document}")[0]
    # The source's own title and maketitle are replaced by the JAIR preamble's.
    body = re.sub(r"\\maketitle\s*", "", body, count=1)

    # acmart requires the abstract before \maketitle, so it is lifted out of the
    # body rather than left where the article class allowed it to sit.
    old_abs, new_abs = structured_abstract(body)
    body = body.replace(old_abs, "", 1)

    # biblatex prints the bibliography; natbib's command is replaced.
    body = re.sub(r"\\bibliographystyle\{[^}]*\}\s*", "", body)
    body = re.sub(r"\\bibliography\{[^}]*\}", r"\\printbibliography", body)
    if r"\printbibliography" not in body:
        body += "\n" + r"\printbibliography" + "\n"

    out = (PREAMBLE + "\n" + new_abs + "\n\n\\maketitle\n" + body
           + CHECKLIST + "\n\\end{document}\n")
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(out)
    n_cite = len(re.findall(r"\\cite[pt]?\{", out))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(out.splitlines())} lines, "
          f"{n_cite} citations")
    return 0


