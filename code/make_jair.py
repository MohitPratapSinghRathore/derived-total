"""Convert the Coherent Errors manuscript to the JAIR submission format.

JAIR rejects submissions not in its format without review, and desk rejects
submissions without a completed reproducibility checklist, so neither is
optional. Since spring 2025 the required style is jair.cls, built on ACM's
acmart, with biblatex and biber rather than natbib.

This is a conversion script rather than a hand edit because the body of the
manuscript still lives in paper/main.tex and will keep changing. Running the
conversion each time keeps the JAIR copy from drifting away from the source, in
the way this project has repeatedly found things drift once a derived artifact
is edited by hand.

What it changes, and nothing else: the document class and preamble, the author
block, the citation commands, and the appended checklist. The body text is taken
verbatim.
"""
