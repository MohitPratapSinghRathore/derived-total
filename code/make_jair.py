def structured_abstract(body: str) -> str:
    """Return the source abstract and a structured replacement for it.

    JAIR encourages structured abstracts. The sections are written out rather
    than inferred from paragraph order, because the source abstract's second
    paragraph is results, not objectives, and an automatic labeller mislabels
    it. The wording is the source's own and every measured value is still a
    \\result macro, so the abstract cannot drift from the result files.

    The guard matters more than the convenience: if the source abstract is
    edited so that these phrases no longer appear, this raises instead of
    emitting a structured abstract that has quietly stopped matching the paper.
    """
    m = re.search(r"\\begin{abstract}(.*?)\\end{abstract}", body, re.S)
    if not m:
        raise SystemExit("no abstract found in the source")
    src = " ".join(m.group(1).split())          # unwrap before matching
    required = [
        "confounds two failures with opposite remedies",
        "Aggregate state fidelity",
        "are legal there",
        "norm-matched random edit",
        "We report failures too",
    ]
    missing = [r for r in required if r not in src]
    if missing:
        raise SystemExit(
            "the source abstract has changed; the structured version in "
            "code/make_jair.py must be rewritten to match. Missing: "
            + "; ".join(missing))

    def M(name):
        return "\\result{" + name + "}"

    parts = [
        ("Background:",
         "Long-horizon failure is reported as one number, which confounds two "
         "failures with opposite remedies: the model has lost track of the "
         "world, or it holds the world and chooses badly."),
        ("Objectives:",
         "We separate the two, and ask the further question a separation alone "
         "leaves open: whether the internal state a probe recovers is merely "
         "present or is actually read by the policy that acts."),
        ("Methods:",
         "We work where an exact state oracle exists, chess from move notation "
         "with no search at inference, in models of " + M("paramsSmall") +
         " to " + M("paramsLarge") + " parameters, reading linear probes "
         "against the true position at every token. Errors are scored against "
         "the board the model appears to believe, with same-depth "
         "mismatched-belief and random-move controls, and the representation "
         "is edited at a calibrated strength against a norm-matched random "
         "direction."),
        ("Results:",
         "Aggregate state fidelity, the quantity usually reported, is the "
         "weaker predictor of an illegal next move within a fixed depth, at "
         "AUC " + M("aucAggMin") + " to " + M("aucAggMax") + " against " +
         M("aucActMin") + " to " + M("aucActMax") + " for the same "
         "representation restricted to the squares the move touches. And the "
         "errors are coherent. Reconstructing the position the model appears "
         "to believe, " + M("belIllAttn") + " of its illegal moves are legal "
         "there, against " + M("belMisAttn") + " for the same move under "
         "another position's belief and " + M("belRandAttn") + " for an "
         "arbitrary illegal move. Editing the probe direction encoding an "
         "occupied square removes " + M("patchCutAttn") + " of the probability "
         "mass on moves from it, a norm-matched random edit " +
         M("patchRandCutAttn") + ", so the representation is read and not "
         "merely present. Belief consistency rises monotonically across six "
         "model sizes, though the causal edit is not measured at every size."),
        ("Conclusions:",
         "A substantial identified subset of long-horizon error is coherent "
         "with a degraded state the policy demonstrably reads. The practical "
         "consequence is a change in what to measure: a world model reported "
         "as an aggregate accuracy tells less than the same representation "
         "scored on the state the next action will consume. We report failures "
         "too: a backwards layer profile, a degenerate pre-registered metric, "
         "an auxiliary objective improving the measurement of state more than "
         "its consequences, and a second domain needing seven designs to "
         "become measurable."),
    ]
    out = ["\\begin{abstract}"]
    for lab, text in parts:
        out.append("{\\bf " + lab + "}" + chr(10) + text + chr(10))
    out.append("\\end{abstract}")
    return m.group(0), chr(10).join(out)


